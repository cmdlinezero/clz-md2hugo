package generator

import (
	"bytes"
	"encoding/json"
	"fmt"
	"os"
	"path/filepath"
	"sort"
	"strings"
	"text/template"
)

const generatedMarker = "<!-- Generated by clz-md2hugo; do not edit directly. -->"

type Result struct{ Changed []string }

type Options struct {
	ConfigPath string
	Check      bool
}

func Run(opts Options) (Result, error) {
	cfg, err := loadConfig(opts.ConfigPath)
	if err != nil {
		return Result{}, err
	}
	base := filepath.Dir(opts.ConfigPath)
	var changed []string
	for _, job := range cfg.Jobs {
		files, err := runJob(base, job, opts.Check)
		if err != nil {
			return Result{}, fmt.Errorf("job %q: %w", job.Name, err)
		}
		changed = append(changed, files...)
	}
	sort.Strings(changed)
	return Result{Changed: changed}, nil
}

func runJob(base string, job Job, check bool) ([]string, error) {
	sourcePath := resolve(base, job.Source)
	templatePath := resolve(base, job.Template)
	outputDir := resolve(base, job.Output)

	sourceBytes, err := os.ReadFile(sourcePath)
	if err != nil {
		return nil, fmt.Errorf("read source: %w", err)
	}
	var source any
	if err := json.Unmarshal(sourceBytes, &source); err != nil {
		return nil, fmt.Errorf("parse source JSON: %w", err)
	}
	items, err := selectItems(source, job.Items)
	if err != nil {
		return nil, err
	}
	items, err = mergeItems(base, items, job.Merge)
	if err != nil {
		return nil, err
	}

	templateBytes, err := os.ReadFile(templatePath)
	if err != nil {
		return nil, fmt.Errorf("read template: %w", err)
	}
	funcs := template.FuncMap{
		"json":  func(v any) (string, error) { b, err := json.Marshal(v); return string(b), err },
		"lower": strings.ToLower,
		"upper": strings.ToUpper,
	}
	bodyTemplate, err := template.New(filepath.Base(templatePath)).Funcs(funcs).Option("missingkey=error").Parse(string(templateBytes))
	if err != nil {
		return nil, fmt.Errorf("parse template: %w", err)
	}
	pathTemplate, err := template.New("path").Funcs(funcs).Option("missingkey=error").Parse(job.Path)
	if err != nil {
		return nil, fmt.Errorf("parse path template: %w", err)
	}

	expected := map[string][]byte{}
	for i, item := range items {
		var pathBuf bytes.Buffer
		if err := pathTemplate.Execute(&pathBuf, item); err != nil {
			return nil, fmt.Errorf("render path for item %d: %w", i+1, err)
		}
		rel := filepath.Clean(pathBuf.String())
		if rel == "." || filepath.IsAbs(rel) || rel == ".." || strings.HasPrefix(rel, ".."+string(filepath.Separator)) {
			return nil, fmt.Errorf("unsafe output path %q", rel)
		}
		var body bytes.Buffer
		if err := bodyTemplate.Execute(&body, item); err != nil {
			return nil, fmt.Errorf("render %s: %w", rel, err)
		}
		content := addGeneratedMarker(body.String())
		if len(content) == 0 || content[len(content)-1] != '\n' {
			content = append(content, '\n')
		}
		expected[filepath.Join(outputDir, rel)] = content
	}

	changed := []string{}
	for path, content := range expected {
		current, err := os.ReadFile(path)
		if err == nil && bytes.Equal(current, content) {
			continue
		}
		if err != nil && !os.IsNotExist(err) {
			return nil, err
		}
		changed = append(changed, path)
		if !check {
			if err := os.MkdirAll(filepath.Dir(path), 0o755); err != nil {
				return nil, err
			}
			if err := writeAtomic(path, content); err != nil {
				return nil, err
			}
		}
	}

	entries, err := generatedFiles(outputDir)
	if err != nil {
		return nil, err
	}
	for _, path := range entries {
		if _, ok := expected[path]; ok {
			continue
		}
		changed = append(changed, path)
		if !check && os.Remove(path) != nil {
			return nil, fmt.Errorf("remove stale generated file %s", path)
		}
	}
	sort.Strings(changed)
	return changed, nil
}

func mergeItems(base string, items []any, merges []Merge) ([]any, error) {
	if len(merges) == 0 {
		return items, nil
	}

	merged := make([]any, len(items))
	for i, item := range items {
		record, ok := item.(map[string]any)
		if !ok {
			return nil, fmt.Errorf("merge requires primary item %d to be a JSON object", i+1)
		}
		copyRecord := make(map[string]any, len(record)+len(merges))
		for key, value := range record {
			copyRecord[key] = value
		}
		merged[i] = copyRecord
	}

	for mergeIndex, spec := range merges {
		data, err := os.ReadFile(resolve(base, spec.Source))
		if err != nil {
			return nil, fmt.Errorf("merge %d read source: %w", mergeIndex+1, err)
		}
		var source any
		if err := json.Unmarshal(data, &source); err != nil {
			return nil, fmt.Errorf("merge %d parse source JSON: %w", mergeIndex+1, err)
		}
		records, err := selectMergeItems(source, spec.Items)
		if err != nil {
			return nil, fmt.Errorf("merge %d: %w", mergeIndex+1, err)
		}
		index := map[string]map[string]any{}
		for i, item := range records {
			record, ok := item.(map[string]any)
			if !ok {
				return nil, fmt.Errorf("merge %d item %d must be a JSON object", mergeIndex+1, i+1)
			}
			key, err := joinKey(record, spec.ForeignKey)
			if err != nil {
				return nil, fmt.Errorf("merge %d item %d: %w", mergeIndex+1, i+1, err)
			}
			if _, exists := index[key]; exists {
				return nil, fmt.Errorf("merge %d has duplicate foreign key %q", mergeIndex+1, key)
			}
			index[key] = record
		}

		for i := range merged {
			record := merged[i].(map[string]any)
			if _, exists := record[spec.As]; exists {
				return nil, fmt.Errorf("merge %d alias %q collides with primary item %d", mergeIndex+1, spec.As, i+1)
			}
			key, err := joinKey(record, spec.LocalKey)
			if err != nil {
				return nil, fmt.Errorf("primary item %d: %w", i+1, err)
			}
			foreign, exists := index[key]
			if !exists {
				return nil, fmt.Errorf("merge %d found no match for %s=%q", mergeIndex+1, spec.LocalKey, key)
			}
			record[spec.As] = foreign
		}
	}
	return merged, nil
}

func selectMergeItems(source any, key string) ([]any, error) {
	if key != "" {
		return selectItems(source, key)
	}
	if items, ok := source.([]any); ok {
		return items, nil
	}
	object, ok := source.(map[string]any)
	if !ok {
		return nil, fmt.Errorf("merge source must be a JSON array or object")
	}
	keys := make([]string, 0, len(object))
	for key := range object {
		keys = append(keys, key)
	}
	sort.Strings(keys)
	items := make([]any, 0, len(keys))
	for _, key := range keys {
		items = append(items, object[key])
	}
	return items, nil
}

func joinKey(record map[string]any, key string) (string, error) {
	value, exists := record[key]
	if !exists {
		return "", fmt.Errorf("join key %q not found", key)
	}
	switch value := value.(type) {
	case string:
		if value == "" {
			return "", fmt.Errorf("join key %q is empty", key)
		}
		return value, nil
	case float64, bool:
		return fmt.Sprint(value), nil
	default:
		return "", fmt.Errorf("join key %q must be a scalar", key)
	}
}

func selectItems(source any, key string) ([]any, error) {
	value := source
	if key != "" {
		m, ok := source.(map[string]any)
		if !ok {
			return nil, fmt.Errorf("items %q requires a JSON object source", key)
		}
		var exists bool
		value, exists = m[key]
		if !exists {
			return nil, fmt.Errorf("items key %q not found", key)
		}
	}
	items, ok := value.([]any)
	if !ok {
		return nil, fmt.Errorf("selected source data must be a JSON array")
	}
	return items, nil
}

func resolve(base, path string) string {
	if filepath.IsAbs(path) {
		return path
	}
	return filepath.Clean(filepath.Join(base, path))
}

func writeAtomic(path string, content []byte) error {
	tmp, err := os.CreateTemp(filepath.Dir(path), ".clz-md2hugo-*")
	if err != nil {
		return err
	}
	name := tmp.Name()
	defer os.Remove(name)
	if _, err := tmp.Write(content); err != nil {
		tmp.Close()
		return err
	}
	if err := tmp.Close(); err != nil {
		return err
	}
	return os.Rename(name, path)
}

func generatedFiles(root string) ([]string, error) {
	var files []string
	err := filepath.WalkDir(root, func(path string, entry os.DirEntry, err error) error {
		if err != nil {
			if os.IsNotExist(err) {
				return nil
			}
			return err
		}
		if entry.IsDir() {
			return nil
		}
		data, err := os.ReadFile(path)
		if err != nil {
			return err
		}
		if hasGeneratedMarker(data) {
			files = append(files, path)
		}
		return nil
	})
	if os.IsNotExist(err) {
		return files, nil
	}
	return files, err
}

func addGeneratedMarker(rendered string) []byte {
	body := strings.TrimLeft(rendered, "\n")
	if end, ok := frontMatterEnd(body); ok {
		return []byte(body[:end] + "\n" + generatedMarker + "\n" + strings.TrimLeft(body[end:], "\n"))
	}
	return []byte(generatedMarker + "\n" + body)
}

func hasGeneratedMarker(data []byte) bool {
	if bytes.HasPrefix(data, []byte(generatedMarker+"\n")) {
		return true
	}
	body := string(data)
	end, ok := frontMatterEnd(body)
	if !ok {
		return false
	}
	remainder := strings.TrimLeft(body[end:], "\n")
	return strings.HasPrefix(remainder, generatedMarker+"\n") || remainder == generatedMarker
}

func frontMatterEnd(body string) (int, bool) {
	var delimiter string
	switch {
	case strings.HasPrefix(body, "---\n"):
		delimiter = "---"
	case strings.HasPrefix(body, "+++\n"):
		delimiter = "+++"
	default:
		return 0, false
	}

	offset := len(delimiter) + 1
	for offset <= len(body) {
		next := strings.IndexByte(body[offset:], '\n')
		var line string
		var lineEnd int
		if next < 0 {
			line = body[offset:]
			lineEnd = len(body)
		} else {
			line = body[offset : offset+next]
			lineEnd = offset + next + 1
		}
		if strings.TrimSuffix(line, "\r") == delimiter {
			return lineEnd, true
		}
		if next < 0 {
			break
		}
		offset = lineEnd
	}
	return 0, false
}
